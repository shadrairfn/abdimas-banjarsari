const OUTSIDE_NUMBERS = new Set([34, 38, 43]);

function hash(input: string) {
  let result = 2166136261;
  for (let index = 0; index < input.length; index += 1) {
    result ^= input.charCodeAt(index);
    result = Math.imul(result, 16777619);
  }
  return Math.abs(result);
}

function classify(products: string): Umkm["subCategory"] {
  const value = products.toUpperCase();
  if (/ES |MINUMAN|JUS|SAKOTENG|SEKOTENG|CINCAU|SOP BUAH/.test(value)) return "Minuman";
  if (/KUE|BOLU|ROTI|DONAT|MOCHI|LAPIS/.test(value)) return "Kue & Roti";
  if (/NASI|LOTEK|GADO|KUPAT|URAP|SEMUR|OREK|PAIS|SEBLAK|CUANKI|BATAGOR|BASO TAHU/.test(value)) return "Makanan";
  return "Camilan";
}

function estimateCoordinates(row: RawUmkm) {
  const [sourceNo, , address] = row;
  const upperAddress = address.toUpperCase();
  let base = BANJARSARI_CENTER;

  if (upperAddress.includes("CILOA")) base = { latitude: -7.2372, longitude: 107.8377 };
  if (upperAddress.includes("CIBODAS")) base = { latitude: -7.2402, longitude: 107.8414 };
  if (upperAddress.includes("SINDANG LAYA") || upperAddress.includes("SINDANGLAYA")) base = { latitude: -7.2347, longitude: 107.8407 };
  if (upperAddress.includes("PALNUNJUK")) base = { latitude: -7.2422, longitude: 107.8386 };

  if (sourceNo === 34) base = { latitude: -7.195, longitude: 107.895 };
  if (sourceNo === 38) base = { latitude: -7.175, longitude: 107.804 };
  if (sourceNo === 43) base = { latitude: -7.221, longitude: 107.875 };

  const seed = hash(`${sourceNo}-${address}`);
  const latJitter = ((seed % 1000) / 1000 - 0.5) * 0.0018;
  const lngJitter = (((Math.floor(seed / 1000) % 1000) / 1000) - 0.5) * 0.0018;

  return {
    latitude: base.latitude + latJitter,
    longitude: base.longitude + lngJitter,
  };
}

export const umkmData: Umkm[] = rawUmkm.map((row) => {
  const [sourceNo, ownerName, address, brand, products] = row;
  const coordinates = estimateCoordinates(row);
  return {
    id: `umkm-${String(sourceNo).padStart(3, "0")}`,
    sourceNo,
    ownerName,
    brand,
    products,
    address,
    category: "Kuliner",
    subCategory: classify(products),
    latitude: coordinates.latitude,
    longitude: coordinates.longitude,
    locationStatus: OUTSIDE_NUMBERS.has(sourceNo) ? "outside" : "estimated",
  };
});

export function getUmkmById(id: string) {
  return umkmData.find((item) => item.id === id);
}
